const isFinishedClass = styles.isFinished!;

export function AnimatedLogo({
  className,
  ariaLabel = "ropejumping",
  replayOnClick = true,
}: AnimatedLogoProps) {
  const reactId = useId().replace(/:/g, "");
  const shapeId = `${reactId}-rope-logo-shape`;
  const clipId = `${reactId}-rope-logo-clip`;
  const revealId = `${reactId}-logo-reveal`;
  const revealRectId = `${reactId}-reveal-rect`;
  const sprayLayerId = `${reactId}-spray-layer`;
  const svgRef = useRef<SVGSVGElement | null>(null);
  const revealRectRef = useRef<SVGRectElement | null>(null);
  const sprayLayerRef = useRef<SVGGElement | null>(null);
  const animationFrameRef = useRef<number | null>(null);
  const shadowTimeoutRef = useRef<number | null>(null);
  const dotTimeoutsRef = useRef<number[]>([]);
  const runIdRef = useRef(0);

  const clearRun = useCallback(() => {
    runIdRef.current += 1;

    if (animationFrameRef.current !== null) {
      cancelAnimationFrame(animationFrameRef.current);
      animationFrameRef.current = null;
    }

    if (shadowTimeoutRef.current !== null) {
      window.clearTimeout(shadowTimeoutRef.current);
      shadowTimeoutRef.current = null;
    }

    dotTimeoutsRef.current.forEach((timeoutId) => {
      window.clearTimeout(timeoutId);
    });
    dotTimeoutsRef.current = [];
    sprayLayerRef.current?.replaceChildren();
  }, []);

  const createSprayDot = useCallback((x: number) => {
    const sprayLayer = sprayLayerRef.current;
    if (!sprayLayer) return;

    const dot = document.createElementNS(SVG_NS, "circle");
    dot.setAttribute("cx", String(randomBetween(x - 10, x + 18)));
    dot.setAttribute("cy", String(randomBetween(-8, 92)));
    dot.setAttribute("r", String(randomBetween(0.8, 3.2)));
    dot.style.opacity = "0";

    sprayLayer.appendChild(dot);
    dot.animate(
      [
        { opacity: 0, transform: "scale(0.2)", filter: "blur(1.4px)" },
        { opacity: 0.85, transform: "scale(1)", filter: "blur(0.2px)" },
        { opacity: 0, transform: "scale(2.6)", filter: "blur(1.6px)" },
      ],
      {
        duration: randomBetween(480, 760),
        easing: "ease-out",
        fill: "forwards",
      },
    );

    const timeoutId = window.setTimeout(() => {
      dot.remove();
      dotTimeoutsRef.current = dotTimeoutsRef.current.filter(
        (currentTimeoutId) => currentTimeoutId !== timeoutId,
      );
    }, 800);
    dotTimeoutsRef.current.push(timeoutId);
  }, []);

  const finishImmediately = useCallback(() => {
    clearRun();
    revealRectRef.current?.setAttribute("width", String(revealMaxWidth));
    svgRef.current?.classList.add(isFinishedClass);
  }, [clearRun]);

  const animateLogo = useCallback(() => {
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      finishImmediately();
      return;
    }

    clearRun();

    const svg = svgRef.current;
    const revealRect = revealRectRef.current;
    if (!svg || !revealRect) return;

    const currentRunId = runIdRef.current;
    svg.classList.remove(isFinishedClass);
    revealRect.setAttribute("width", "0");

    let start: number | null = null;
    let lastDot = 0;

    const frame = (time: number) => {
      if (currentRunId !== runIdRef.current) return;
      start ??= time;

      const progress = Math.min((time - start) / revealDuration, 1);
      const eased = easeOutCubic(progress);
      const currentWidth = revealMaxWidth * eased;

      revealRect.setAttribute("width", String(currentWidth));

      if (time - lastDot > 26 && progress < 0.985) {
        createSprayDot(-30 + currentWidth);
        lastDot = time;
      }

      if (progress < 1) {
        animationFrameRef.current = requestAnimationFrame(frame);
        return;
      }

      animationFrameRef.current = null;
      shadowTimeoutRef.current = window.setTimeout(() => {
        if (currentRunId !== runIdRef.current) return;
        svg.classList.add(isFinishedClass);
        shadowTimeoutRef.current = null;
      }, 220);
    };

    animationFrameRef.current = requestAnimationFrame(frame);
  }, [clearRun, createSprayDot, finishImmediately]);

  useEffect(() => {
    animateLogo();

    return () => {
      clearRun();
    };
  }, [animateLogo, clearRun]);

  const handleClick = () => {
    if (replayOnClick) {
      animateLogo();
    }
  };

  return (
    <svg
      ref={svgRef}
      className={[
        styles.logo,
        replayOnClick ? styles.isReplayable : "",
        className ?? "",
      ]
        .filter(Boolean)
        .join(" ")}
      viewBox="0 0 862.504 82.1472"
      xmlns="http://www.w3.org/2000/svg"
      role="img"
      aria-label={ariaLabel}
      onClick={handleClick}
    >
      <defs>
        <g id={shapeId} className={styles.logoShape}>
          {logoPaths.map((pathData) => (
            <path key={pathData} d={pathData} fillRule="evenodd" />
          ))}
        </g>

        <clipPath id={clipId} clipPathUnits="userSpaceOnUse">
          <use href={`#${shapeId}`} />
        </clipPath>

        <clipPath id={revealId} clipPathUnits="userSpaceOnUse">
          <rect
            ref={revealRectRef}
            id={revealRectId}
            x="-30"
            y="-30"
            width="0"
            height="150"
          />
        </clipPath>
      </defs>

      <g
        ref={sprayLayerRef}
        id={sprayLayerId}
        className={styles.sprayLayer}
        clipPath={`url(#${clipId})`}
      />
      <use
        className={styles.logoShadow}
        href={`#${shapeId}`}
        clipPath={`url(#${revealId})`}
      />
      <use
        className={styles.logoFinal}
        href={`#${shapeId}`}
        clipPath={`url(#${revealId})`}
      />
    </svg>
  );
}

function easeOutCubic(t: number) {
  return 1 - Math.pow(1 - t, 3);
}

function randomBetween(min: number, max: number) {
  return min + Math.random() * (max - min);
}
